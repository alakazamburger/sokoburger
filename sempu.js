function resizedWindow() {
  var w = window.innerWidth
  var h = window.innerHeight
  const gw = GLOBWIDTH
  const gh = GLOBHEIGHT
  
  // check which is the 'limiting factor' for 16x9, and size w & h to fit this
  var wratio = (gh/gw) * w
  var hratio = h
  if (wratio > hratio) {
    w = (gw/gh) * h
  } else {
    h = wratio
  }
  
  // add padding
  w *= 0.9
  h *= 0.9
  
  // make them divisible by 9 and 16 (respectively)
  w = Math.floor(w/gw)*gw
  h = Math.floor(h/gh)*gh
  
  // actually set it
  const mainDiv = document.getElementById("gameWindow")
  mainDiv.width = w
  mainDiv.height = h
  canvas.width = w
  canvas.height = h
  topCanvas.width = w
  topCanvas.height = h
  cursorCanvas.width = w
  cursorCanvas.height = h
  
  // same for the menu
  const menuDiv = document.getElementById("menu")
  var mw = w*0.8
  var mh = h*0.7
  menuDiv.style.width = `${mw}px`
  menuDiv.style.height = `${mh}px`
  
  // update the global variables
  cwidth = w
  cheight = h
  twidth = w/GLOBWIDTH
  theight = h/GLOBHEIGHT
  // console.log(w,h)
  // console.log(twidth,theight)
  
  if (renderedOnce === true) {
    renderBaseLayer()
    renderIconLayer()
  }
}

